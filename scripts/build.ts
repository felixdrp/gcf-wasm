// Build every WebAssembly module into dist/.
//
//   dist/gcf.wasm               the codec: src/wat/*.wat, no name section (shipped)
//   dist/gcf.debug.wasm         the same module with function names
//   dist/gcf_simd.wasm          src/gcf_simd.wat, the structural indexer
//   dist/gcf_simd.relaxed.wasm  the same with relaxed-SIMD swizzles
//   dist/gcf_zig.wasm           the Zig reference build (reference/gcf-zig),
//                               only for differential tests and benchmarks
//
// The reference build needs the git submodule and Zig. Without them it is
// skipped with a notice (GCF_REQUIRE_ORACLE=1 makes that an error, as in CI).
import wabtInit from "wabt";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const dist = join(root, "dist");
mkdirSync(dist, { recursive: true });

const wabt = await wabtInit();
const watPath = join(root, "src/gcf_simd.wat");
const watSource = readFileSync(watPath, "utf8");

// Two builds of the indexer from one source:
//   gcf_simd.wasm          baseline SIMD128, runs on every SIMD-capable engine
//   gcf_simd.relaxed.wasm  every `i8x16.swizzle ;; @relaxed` becomes
//                          `i8x16.relaxed_swizzle` (relaxed-SIMD proposal).
// The marked swizzles only ever see indices 0..15, the range where relaxed
// and strict swizzle are defined to agree, so both builds compute identical
// results. The relaxed form maps to a bare `pshufb`/`tbl` without the
// out-of-range fix-up. Hosts load it when `WebAssembly.validate` accepts it.
const variants: [string, string, Record<string, boolean>][] = [
  ["gcf_simd.wasm", watSource, { simd: true }],
  ["gcf_simd.relaxed.wasm", watSource.replaceAll("i8x16.swizzle ;; @relaxed", "i8x16.relaxed_swizzle ;; @relaxed"), { simd: true, relaxed_simd: true }],
];
for (const [out, text, features] of variants) {
  const mod = wabt.parseWat(watPath, text, features);
  mod.validate();
  const { buffer } = mod.toBinary({ log: false, write_debug_names: true });
  writeFileSync(join(dist, out), buffer);
  mod.destroy();
}

// The codec: src/wat/*.wat concatenated into one module (tables generated by
// scripts/gen-wat-tables.ts; all code is hand-written).
{
  const { generate, selfCheck } = await import("./gen-wat-tables.ts");
  selfCheck();
  const watDir = join(root, "src/wat");
  writeFileSync(join(watDir, "_tables.gen.wat"), generate());
  // A failed compile must not leave the previous module behind.
  rmSync(join(dist, "gcf.wasm"), { force: true });
  rmSync(join(dist, "gcf.debug.wasm"), { force: true });
  const parts = readdirSync(watDir).filter((f) => f.endsWith(".wat")).sort();
  const text = "(module\n" + parts.map((f) => `;; ---- ${f} ----\n` + readFileSync(join(watDir, f), "utf8")).join("\n") + "\n)\n";
  const mod = wabt.parseWat("gcf.wat", text, { simd: true, bulk_memory: true, multi_value: true, sign_extension: true, sat_float_to_int: true });
  mod.validate();
  // gcf.debug.wasm keeps function names (readable traps and profiles) for
  // development; gcf.wasm is the same code without the name section, shipped
  // in the npm package and the release (same speed, ~17 KB less).
  writeFileSync(join(dist, "gcf.debug.wasm"), mod.toBinary({ log: false, write_debug_names: true }).buffer);
  writeFileSync(join(dist, "gcf.wasm"), mod.toBinary({ log: false, write_debug_names: false }).buffer);
  mod.destroy();
}

const built = ["gcf.wasm", "gcf.debug.wasm", "gcf_simd.wasm", "gcf_simd.relaxed.wasm"];

// The Zig reference build: `zig build wasm` in the gcf-zig submodule (flags
// live in its build.zig: wasm32-freestanding, simd128, ReleaseFast, stripped).
{
  const ref = join(root, "reference/gcf-zig");
  const required = process.env.GCF_REQUIRE_ORACLE === "1";
  const skip = (why: string) => {
    if (required) {
      console.error(`dist/gcf_zig.wasm: ${why}`);
      process.exit(1);
    }
    rmSync(join(dist, "gcf_zig.wasm"), { force: true });
    console.warn(`skipped dist/gcf_zig.wasm (${why}); the differential tests against Zig will not run`);
  };
  if (!existsSync(join(ref, "build.zig"))) {
    skip("reference/gcf-zig is empty: git submodule update --init");
  } else {
    const zig = Bun.spawnSync(["zig", "build", "wasm"], { cwd: ref, stdout: "inherit", stderr: "inherit" });
    if (zig.exitCode !== 0) skip("zig build wasm failed in reference/gcf-zig");
    else {
      writeFileSync(join(dist, "gcf_zig.wasm"), readFileSync(join(ref, "zig-out/wasm/gcf.wasm")));
      built.push("gcf_zig.wasm");
    }
  }
}

for (const f of built) console.log(`built dist/${f} (${readFileSync(join(dist, f)).length} bytes)`);
